// 单句形态：保持 body = bodies[0]，旧调用方（只读 body）行为不变
GIFT_NOTE_PRESETS.forEach((preset) => {
  if (Array.isArray(preset.bodies) && preset.bodies.length) preset.body = preset.bodies[0]
})

function getPresetById(id) {
  const key = String(id || '').trim()
  if (!key) return null
  return GIFT_NOTE_PRESETS.find((p) => p.id === key) || null
}

/** 候选句数（无 bodies 的临时预设按 0 计，调用方自行回落） */
function presetBodyCount(preset) {
  return (preset && Array.isArray(preset.bodies) && preset.bodies.length) || 0
}

/**
 * 取该关系的第 index 句：自动取模（负数也安全）。
 * 没有 bodies 的临时预设（如场景语向）回落到 preset.body —— 行为与改动前一致。
 */
function pickPresetBody(preset, index) {
  const list = (preset && Array.isArray(preset.bodies) && preset.bodies.length) ? preset.bodies : null
  if (!list) return String((preset && preset.body) || '')
  const n = list.length
  const i = (((Number(index) || 0) % n) + n) % n
  return list[i]
}

