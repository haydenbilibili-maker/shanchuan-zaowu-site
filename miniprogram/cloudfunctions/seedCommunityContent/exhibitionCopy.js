function applyExhibitionCopy(seedKey) {
  const copy = COPIES[seedKey]
  if (!copy) {
    return {
      brief: '',
      tags: ['专题'],
      relatedArticleSeedKeys: [],
      relatedProductIds: [],
      relatedSkus: [],
      content: ''
    }
  }
  const imgMap = IMAGE_SETS[seedKey] || {}
  const sections = copy.sections.map((s, i) => ({
    ...s,
    images: s.images || imgMap[i] || []
  }))
  return {
    brief: copy.brief,
    tags: copy.tags,
    relatedArticleSeedKeys: copy.relatedArticleSeedKeys || [],
    relatedProductIds: [],
    relatedSkus: [],
    content: sectionsToHtml(sections)
  }
}

