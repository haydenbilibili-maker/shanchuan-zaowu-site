function identityOf(roleId) {
  const r = STAFF_ROLES[roleId]
  if (!r) return ''
  return `你叫${r.person}，是山海造物标本艺术馆的${r.name}。你的履历：${r.cv.join('；')}。你的口头禅是「${r.motto}」。说话方式：${r.voice}`
}

function systemPromptOf(roleId) {
  const role = STAFF_ROLES[roleId]
  if (!role) return ''
  return `${identityOf(roleId)}\n${role.prompt}\n\n${STAFF_SYSTEM_SUFFIX}`
}

/** 称呼：「林晓棠（门店运营经理）」—— 辩论与主动提醒里用 */
function displayOf(roleId) {
  const r = STAFF_ROLES[roleId]
  return r ? `${r.person}（${r.name}）` : ''
}

